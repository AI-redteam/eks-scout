def main():
    """Main CLI entry point."""
    logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')

    parser = argparse.ArgumentParser(
        prog="eks-scout",
        description="EKS Scout - Passive Security Scanner for AWS EKS"
    )
    subparsers = parser.add_subparsers(dest="command", help="Available commands")

    # --- scan subcommand ---
    scan_parser = subparsers.add_parser("scan", help="Run a security scan against an EKS cluster")
    scan_parser.add_argument("--cluster-name", required=True, help="Name of the EKS cluster")
    scan_parser.add_argument("--region", required=True, help="AWS region of the EKS cluster")
    scan_parser.add_argument("--profile", help="AWS CLI profile to use")
    scan_parser.add_argument("--context", help="kubectl context to use")
    scan_parser.add_argument("-o", "--output-file", default="eks_findings_plextrac.csv",
                             help="Output file name (default: eks_findings_plextrac.csv)")
    scan_parser.add_argument("-f", "--output-format", choices=['csv', 'json'], default='csv',
                             help="Output format (default: csv)")
    scan_parser.add_argument("--config", help="Path to configuration file (YAML or JSON)")
    scan_parser.add_argument("--show-suppressed", action="store_true",
                             help="Include suppressed findings in output with 'Suppressed' status")
    scan_parser.add_argument("--debug", action="store_true", help="Enable debug logging")
    scan_parser.add_argument("--fail-on", choices=['critical', 'high', 'medium', 'low'],
                             help="Exit with code 2 if any finding meets or exceeds this severity (for CI/CD gating)")

    # --- init subcommand ---
    init_parser = subparsers.add_parser("init", help="Generate a default configuration file")
    init_parser.add_argument("-o", "--output", help="Output file path (default: eks-scout.yaml)")
    init_parser.add_argument("--force", action="store_true", help="Overwrite existing config file")

    args = parser.parse_args()

    if args.command == "scan":
        if args.debug:
            logging.getLogger().setLevel(logging.DEBUG)
        cmd_scan(args)
    elif args.command == "init":
        cmd_init(args)
    else:
        parser.print_help()
        sys.exit(1)
