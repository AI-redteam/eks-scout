def cmd_scan(args):
    """Execute the scan subcommand."""
    print(BANNER)

    start_time = datetime.now()
    logging.info(f"Starting EKS Scout scan for cluster '{args.cluster_name}' in region '{args.region}'...")
    logging.info(f"Using AWS Profile: '{args.profile or 'default'}' | Using kubectl Context: '{args.context or 'default'}'")
    logging.info("NOTE: This tool uses read-only kubectl and aws cli commands.")

    result = scan(
        cluster_name=args.cluster_name,
        region=args.region,
        profile=args.profile,
        context=args.context,
        config_file=args.config,
        show_suppressed=getattr(args, 'show_suppressed', False),
    )

    if result is None:
        logging.error("Scan aborted due to dependency check failure.")
        sys.exit(1)

    end_time = datetime.now()
    duration = end_time - start_time
    logging.info(f"--- Scan Complete (duration: {duration}) ---")

    if not result.findings and not result.suppressed:
        logging.info("No specific security issues found based on the current checks.")
        return

    # Print console summary
    print_summary(result.findings, suppressed_count=result.suppressed_count,
                  combos=result.combos, duration=duration)

    # Export results (active findings, plus suppressed if --show-suppressed)
    export_findings = result.all_findings
    output_file = args.output_file
    if args.output_format == 'csv':
        export_findings_to_csv(export_findings, output_file)
    elif args.output_format == 'json':
        export_findings_to_json(export_findings, output_file, combos=result.combos)

    # CI/CD exit code gating
    fail_on = getattr(args, 'fail_on', None)
    if fail_on:
        threshold = SEVERITY_RANK[fail_on.capitalize()]
        for finding in result.findings:
            finding_rank = SEVERITY_RANK.get(finding.get('severity', ''), 99)
            if finding_rank <= threshold:
                logging.error(f"Failing: found finding with severity '{finding['severity']}' "
                              f"(threshold: {fail_on})")
                sys.exit(2)
        logging.info(f"No findings at or above '{fail_on}' severity. Exiting 0.")


def cmd_init(args):
    """Generate a default configuration file."""
    import os

    output = args.output or "eks-scout.yaml"
    if os.path.exists(output) and not args.force:
        print(f"Config file '{output}' already exists. Use --force to overwrite.")
        sys.exit(1)

    config_content = _generate_default_config()
    with open(output, 'w') as f:
        f.write(config_content)
    print(f"Generated default configuration file: {output}")
    print("Edit this file to customize checks, suppressions, and settings.")


